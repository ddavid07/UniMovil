import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { chmod, readFile, writeFile } from 'node:fs/promises';
import { URL } from 'node:url';

const existing = await readFile('.env.local', 'utf8').catch(() => '');
const existingValues = Object.fromEntries(
  existing
    .split('\n')
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => {
      const separator = line.indexOf('=');
      return [line.slice(0, separator), line.slice(separator + 1)];
    }),
);

const statusArgs = ['supabase', 'status', '--env', '--output-format', 'json'];
let statusOutput;
try {
  statusOutput = execFileSync('npx', statusArgs, { encoding: 'utf8' });
} catch {
  statusOutput = execFileSync('npx', statusArgs, {
    encoding: 'utf8',
    env: { ...process.env, SUPABASE_EXPERIMENTAL_STACK: '1' },
  });
}
const environment = JSON.parse(statusOutput);
const databaseUrl = new URL(environment.DB_URL);
const runtimePassword =
  existingValues.RUNTIME_DB_PASSWORD ?? randomBytes(24).toString('hex');
const runtimeDatabaseUrl = new URL(databaseUrl);
runtimeDatabaseUrl.username = 'unimovil_runtime';
runtimeDatabaseUrl.password = runtimePassword;

const values = {
  API_PORT: '3001',
  WEB_APP_URL: 'http://localhost:8081',
  WEB_ORIGINS: 'http://localhost:8081,http://127.0.0.1:8081',
  SUPABASE_URL: environment.API_URL,
  SUPABASE_ANON_KEY: environment.ANON_KEY,
  SUPABASE_SERVICE_ROLE_KEY: environment.SERVICE_ROLE_KEY,
  MIGRATION_DATABASE_URL: environment.DB_URL,
  DATABASE_URL: runtimeDatabaseUrl.toString(),
  RUNTIME_DB_PASSWORD: runtimePassword,
  WEB_SESSION_ENCRYPTION_KEY:
    existingValues.WEB_SESSION_ENCRYPTION_KEY ?? randomBytes(32).toString('base64'),
  EXPO_PUBLIC_SUPABASE_URL: environment.API_URL,
  EXPO_PUBLIC_SUPABASE_ANON_KEY: environment.ANON_KEY,
  EXPO_PUBLIC_API_URL: 'http://localhost:3001/api',
};

await writeFile(
  '.env.local',
  `# Local Supabase credentials. Generated by npm run local:env. Never commit this file.\n${Object.entries(
    values,
  )
    .map(([key, value]) => `${key}=${value}`)
    .join('\n')}\n`,
  { mode: 0o600 },
);
await chmod('.env.local', 0o600);
console.log('Wrote local-only .env.local with restrictive permissions.');
